#!/usr/bin/env python3
"""Generate project-scoped Codex agents from the installed OpenCode profiles."""
from pathlib import Path
import json
import tomllib

ROOT = Path(__file__).resolve().parents[1]
NAMES = (
    "fastapi-developer expo-react-native-expert postgres-pro terraform-engineer "
    "test-automator debugger llm-architect prompt-engineer cloud-architect "
    "code-reviewer security-auditor"
).split()
DEST = ROOT / ".codex" / "agents"
DEST.mkdir(parents=True, exist_ok=True)
for name in NAMES:
    source = ROOT / ".opencode" / "agents" / f"{name}.md"
    _, front, body = source.read_text().split("---", 2)
    description_line = next(line for line in front.splitlines() if line.startswith("description:"))
    description = description_line.partition(":")[2].strip().strip('"')
    readonly = name in {"code-reviewer", "security-auditor"}
    prefix = (
        "You are working on SpillTheReel. Read root AGENTS.md and the assigned task "
        "in docs/LUNA_IMPLEMENTATION_PLAN.md. Project instructions override generic "
        "upstream recommendations. Stay inside the file ownership assigned by the parent. "
        "Do not upgrade frameworks, deploy, run paid extraction, or modify live databases "
        "as a side effect. Return changed files, evidence, checks, and remaining risks. "
        "Do not spawn nested agents; return requests for additional specialists to the parent. "
        "If an upstream profile mentions a context manager, ask the parent or read project "
        "docs; do not invent tools.\n\n"
    )
    if readonly:
        prefix += (
            "READ-ONLY REVIEW: do not edit files, run shell commands, or mutate external "
            "services. Report actionable findings with file paths and reproduction evidence. "
            "Codex inherits parent permissions; this instruction is not a separate sandbox.\n\n"
        )
    text = (
        "# Generated by scripts/convert-codex-agents.py; upstream source in .opencode/agents.\n"
        f"name = {json.dumps(name)}\n"
        f"description = {json.dumps(description)}\n"
        'model = "gpt-6-luna"\n'
        'model_reasoning_effort = "high"\n'
        f"developer_instructions = {json.dumps(prefix + body.strip())}\n"
    )
    if readonly:
        text += "\n[features]\nshell_tool = false\n"
    tomllib.loads(text)
    (DEST / f"{name}.toml").write_text(text)
print(f"Generated and TOML-validated {len(NAMES)} Codex agent profiles.")
